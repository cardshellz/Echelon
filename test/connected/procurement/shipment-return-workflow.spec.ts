import { test, expect, login, type Backend } from "./fixtures";

type Row = Record<string, unknown>;
interface WorkflowState { shipments: Row[]; shipmentLines: Row[]; receipts: Row[]; receivingLines: Row[];
  purchaseLines: Row[]; lots: Row[]; transactions: Row[]; returns: Row[]; returnLines: Row[]; returnCosts: Row[];
  payments: Row[]; credits: Row[]; quantityCommands: Row[]; receiptCostAttempts: Row[] }
const state = (backend: Backend) => backend.control<WorkflowState>("workflow-state");

test("draft shipment preserves case setup through booking, receipt and recovered accepted-stock return", async ({ page, backend }, info) => {
  const actor = backend.actors.find(candidate => candidate.id === "connected-financial");
  if (!actor) throw new Error("Missing connected financial actor");
  await login(page, backend, actor);
  const initial = await state(backend);
  await page.goto(backend.url + "/purchase-orders/14?tab=shipments");
  await page.getByRole("button", { name: "Create Shipment", exact: true }).click();
  const create = page.getByRole("dialog", { name: "Create Inbound Shipment", exact: true });
  await create.getByPlaceholder("e.g. SHP-2026-042", { exact: true }).fill("CONNECTED-SETUP-SHIPMENT");
  await create.getByRole("combobox", { name: "Count unit create-shipment-line-23", exact: true }).selectOption("101");
  await expect(create.locator("#create-shipment-line-23-quantity")).toHaveValue("20");
  await expect(create.getByLabel("Quantity entry create-shipment-line-23", { exact: true })).toContainText("100 pieces shipped");
  await create.getByRole("button", { name: "Create Shipment", exact: true }).click();
  await expect(page).toHaveURL(/\/shipments\/\d+/);
  const created = await state(backend);
  const shipment = created.shipments.find(row => row.shipment_number === "CONNECTED-SETUP-SHIPMENT");
  expect(shipment).toBeDefined();
  const shipmentId = Number(shipment!.id);
  const shipped = created.shipmentLines.filter(row => row.inbound_shipment_id === shipmentId);
  expect(shipped).toHaveLength(1);
  expect(Number(shipped[0].qty_shipped)).toBe(100);
  await expect(page.getByText("Every item has a valid receiving configuration.", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Confirm", exact: true }).click();
  await expect(page.getByRole("button", { name: "Mark In Transit", exact: true })).toBeEnabled();
  await page.reload();
  await expect(page.getByText("Every item has a valid receiving configuration.", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Mark In Transit", exact: true }).click();
  await page.getByRole("button", { name: "Delivered", exact: true }).click();
  await page.getByRole("button", { name: "Create Receipt", exact: true }).click();
  await expect(page).toHaveURL(/\/receiving\?open=\d+/);
  const receiptId = Number(new URL(page.url()).searchParams.get("open"));
  const prepared = await state(backend);
  const receiptLine = prepared.receivingLines.find(row => row.receiving_order_id === receiptId);
  expect(receiptLine).toBeDefined();
  const lineId = Number(receiptLine!.id);
  expect(Number(receiptLine!.units_per_variant_snapshot)).toBe(5);
  expect(Number(receiptLine!.expected_qty)).toBe(20);
  await page.getByRole("button", { name: "Start receiving", exact: true }).click();
  const warehouse = page.getByRole("combobox", { name: "Receiving warehouse", exact: true });
  if (await warehouse.isVisible()) {
    await warehouse.click();
    await page.getByRole("option", { name: /MAIN/ }).click();
  }
  await page.getByRole("combobox", { name: "Default receiving location", exact: true }).click();
  await page.getByRole("option", { name: /PICK/ }).click();
  await expect.poll(async () => (await state(backend)).receivingLines.find(row => row.id === lineId)?.putaway_location_id).toBe(100);
  await page.getByLabel("Received count for line " + lineId, { exact: true }).filter({ visible: true }).fill("20");
  await page.getByTestId("btn-complete-line-" + lineId).filter({ visible: true }).click();
  await expect(page.getByLabel("Received count confirmed for line " + lineId, { exact: true }).filter({ visible: true })).toBeVisible();
  await page.getByTestId("btn-close-receipt").click();
  await expect.poll(async () => (await state(backend)).receipts.find(row => row.id === receiptId)?.status).toBe("closed");
  await expect.poll(async () => (await state(backend)).receiptCostAttempts.map(row => row.state)).toEqual(["applied"]);
  const received = await state(backend);
  const lot = received.lots.find(row => row.receiving_order_id === receiptId);
  expect(lot).toBeDefined();
  expect(Number(lot!.qty_received)).toBe(20);
  expect(Number(lot!.qty_on_hand)).toBe(20);
  await page.goto(backend.url + "/supplier-returns?new=1&vendorId=5&purchaseOrderId=14&receivingOrderId=" + receiptId);
  await page.getByRole("checkbox", { name: "Return lot " + lot!.lot_number, exact: true }).check();
  await page.locator("#return-" + lot!.id + "-quantity").fill("1");
  await page.getByRole("button", { name: "Review return quantity and value", exact: true }).click();
  const review = page.getByRole("region", { name: "Reviewed physical return", exact: true });
  await expect(review).toContainText("1 recorded units × 5 pieces = 5 pieces to return");
  await review.getByLabel("Collection date", { exact: true }).fill("2026-10-28");
  await review.getByLabel("Collection evidence reference", { exact: true }).fill("CONNECTED-COLLECTION-1");
  await review.getByLabel("Reason for return", { exact: true }).fill("Connected collected case returned with its original receipt provenance");
  await review.getByRole("checkbox", { name: /I verified the collected goods/ }).check();
  const attempts: Array<{ body: string | null; key: string | undefined }> = [];
  await page.route("**/api/supplier-returns", async route => {
    if (route.request().method() !== "POST") return route.continue();
    attempts.push({ body: route.request().postData(), key: route.request().headers()["idempotency-key"] });
    if (attempts.length !== 1) return route.continue();
    const response = await route.fetch({ maxRetries: 0 });
    expect(response.ok(), await response.text()).toBe(true);
    await route.abort("connectionreset");
  });
  await review.getByRole("button", { name: "Record collected supplier return", exact: true }).click();
  await expect.poll(async () => (await state(backend)).returns.length).toBe(1);
  const committed = await state(backend);
  await page.reload();
  await page.getByRole("button", { name: "Recover saved return request", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Supplier return #" + committed.returns[0].id, exact: true })).toBeVisible();
  expect(attempts).toHaveLength(2); expect(attempts[1]).toEqual(attempts[0]);
  const recovered = await state(backend);
  expect(recovered.returns).toEqual(committed.returns);
  expect(recovered.returnLines).toEqual(committed.returnLines);
  expect(recovered.returnCosts).toEqual(committed.returnCosts);
  expect(recovered.transactions).toEqual(committed.transactions);
  expect(recovered.quantityCommands).toEqual(committed.quantityCommands);
  expect(Number(recovered.lots.find(row => row.id === lot!.id)?.qty_on_hand)).toBe(19);
  expect(recovered.receivingLines).toEqual(received.receivingLines);
  expect(recovered.purchaseLines).toEqual(received.purchaseLines);
  expect(recovered.payments).toEqual(initial.payments); expect(recovered.credits).toEqual(initial.credits);
  await info.attach("shipment-receipt-return-evidence", { body: JSON.stringify({ initial, created, received, committed, recovered }, null, 2), contentType: "application/json" });
});
