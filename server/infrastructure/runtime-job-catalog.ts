export function registerExternalRuntimeJobs(): void {
  for (const job of EXTERNAL_RUNTIME_JOBS) {
    registerScheduledJob({
      name: job.name,
      cadenceMs: job.cadenceMs,
      initialDelayMs: job.initialDelayMs ?? 0,
      advisoryLockId: job.advisoryLockId,
      concurrencyMechanism: job.concurrencyMechanism,
      writableStates: job.writableStates,
      deadLetterPolicy: job.deadLetterPolicy,
      disableEnvVar: job.disableEnvVar,
      persistedRunKey: job.persistedRunKey,
      autoStartLoop: false,
      run: noopExternalRun,
    });
  }
}
