import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import { drizzle } from "drizzle-orm/node-postgres";
import { afterAll, beforeAll, beforeEach, describe, expect, it, vi } from "vitest";

import * as schema from "@shared/schema";
import {
  buildShopifyOwnershipGroups,
  shopifyOwnershipRepairRequestHash,
  type ShopifyRemoteProductSnapshot,
} from "../../shopify-product-mapping-reconciliation.domain";
import {
  createShopifyProductMappingReconciliationRepository,
} from "../../shopify-product-mapping-reconciliation.repository";
import {
  createInventoryCutoverTestDatabase,
  type InventoryCutoverTestDatabase,
} from "../../../inventory/__tests__/fixtures/inventory-cutover-database";

const databaseUrl = process.env.ECHELON_TEST_DATABASE_URL;
const disposable = process.env.ECHELON_TEST_DATABASE_DISPOSABLE === "true";
const describeDatabase = databaseUrl && disposable ? describe : describe.skip;
const migration = readFileSync(
  resolve(process.cwd(), "migrations/0665_shopify_ownership_repair_commands.sql"),
  "utf8",
);
const fixtureSql = `
  CREATE SCHEMA catalog;
  CREATE SCHEMA channels;

  CREATE TABLE catalog.shipping_groups (
    id integer PRIMARY KEY,
    code varchar(50) NOT NULL
  );
  CREATE TABLE catalog.products (
    id integer PRIMARY KEY,
    name text NOT NULL,
    sku varchar(100),
    shopify_product_id varchar(100),
    shipping_group_id integer,
    updated_at timestamp NOT NULL DEFAULT now()
  );
  CREATE TABLE catalog.product_variants (
    id integer PRIMARY KEY,
    product_id integer NOT NULL,
    name text NOT NULL,
    sku varchar(100),
    is_active boolean NOT NULL DEFAULT true,
    track_inventory boolean NOT NULL DEFAULT true,
    sales_eligibility varchar(20) NOT NULL DEFAULT 'sellable',
    barcode varchar(100),
    shopify_variant_id varchar(100),
    shopify_inventory_item_id varchar(100),
    updated_at timestamp NOT NULL DEFAULT now()
  );
  CREATE TABLE channels.channels (
    id integer PRIMARY KEY,
    name varchar(100) NOT NULL,
    provider varchar(30) NOT NULL,
    is_default integer NOT NULL DEFAULT 0
  );
  CREATE TABLE channels.channel_connections (
    id integer PRIMARY KEY,
    channel_id integer NOT NULL,
    shop_domain varchar(255),
    access_token text,
    api_version varchar(20),
    updated_at timestamp NOT NULL DEFAULT now()
  );
  CREATE TABLE channels.channel_feeds (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel_id integer,
    product_variant_id integer NOT NULL,
    channel_type varchar(30) NOT NULL DEFAULT 'shopify',
    channel_variant_id varchar(100) NOT NULL,
    channel_product_id varchar(100),
    channel_inventory_item_id varchar(100),
    channel_sku varchar(100),
    is_active integer NOT NULL DEFAULT 1,
    last_synced_qty integer,
    consecutive_push_failures integer NOT NULL DEFAULT 0,
    quarantined_at timestamp,
    quarantine_reason text,
    updated_at timestamp NOT NULL DEFAULT now(),
    UNIQUE(channel_id, product_variant_id)
  );
  CREATE TABLE channels.channel_listings (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel_id integer NOT NULL,
    product_variant_id integer,
    external_product_id varchar(100),
    external_variant_id varchar(100),
    external_url text,
    sync_status varchar(20),
    sync_error text,
    updated_at timestamp NOT NULL DEFAULT now(),
    UNIQUE(channel_id, product_variant_id)
  );
  CREATE TABLE public.audit_events (
    id bigserial PRIMARY KEY,
    timestamp timestamptz NOT NULL DEFAULT now(),
    level text NOT NULL DEFAULT 'AUDIT',
    actor text NOT NULL,
    action text NOT NULL,
    target text,
    changes jsonb,
    context jsonb
  );

  ${migration}
`;

describeDatabase.sequential("Shopify ownership repair PostgreSQL contract", () => {
  let database: InventoryCutoverTestDatabase;
  let repository: ReturnType<
    typeof createShopifyProductMappingReconciliationRepository
  >;
  const remoteProducts = new Map<string, ShopifyRemoteProductSnapshot>([[
    "9001",
    {
      productId: "9001",
      exists: true,
      title: "100PT Toploader",
      status: "ACTIVE",
      shippingGroupCode: "protection",
    },
  ]]);

  beforeAll(async () => {
    database = await createInventoryCutoverTestDatabase(
      databaseUrl,
      disposable,
      fixtureSql,
    );
    repository = createShopifyProductMappingReconciliationRepository(
      drizzle(database.pool, { schema }),
    );
  });

  beforeEach(async () => {
    await database.pool.query(`
      TRUNCATE
        public.audit_events,
        channels.shopify_ownership_repair_commands,
        channels.channel_listings,
        channels.channel_feeds,
        channels.channel_connections,
        channels.channels,
        catalog.product_variants,
        catalog.products,
        catalog.shipping_groups
      RESTART IDENTITY;
      INSERT INTO catalog.shipping_groups(id, code)
      VALUES (1, 'protection');
      INSERT INTO catalog.products(
        id, name, sku, shopify_product_id, shipping_group_id
      ) VALUES
        (10, '100PT Toploader', 'SHLZ-TOP-100PT', '9001', 1),
        (11, 'Archived duplicate', 'OLD-TOP-100PT', '9001', 1);
      INSERT INTO catalog.product_variants(
        id, product_id, name, sku, is_active, sales_eligibility,
        shopify_variant_id, shopify_inventory_item_id
      ) VALUES
        (101, 10, 'Active pack', 'SHLZ-TOP-100PT-P20', true, 'sellable', '2001', '3001'),
        (111, 11, 'Archived pack', 'OLD-TOP-100PT-P20', false, 'sellable', '2002', '3002');
      INSERT INTO channels.channels(id, name, provider, is_default)
      VALUES (36, 'Shopify', 'shopify', 1);
      INSERT INTO channels.channel_connections(
        id, channel_id, shop_domain, access_token, api_version
      ) VALUES (1, 36, 'cardshellz.myshopify.com', 'shpat_test', '2024-01');
      INSERT INTO channels.channel_feeds(
        channel_id, product_variant_id, channel_type, channel_variant_id,
        channel_product_id, channel_inventory_item_id, channel_sku, is_active
      ) VALUES
        (36, 101, 'shopify', '2001', '9001', '3001', 'SHLZ-TOP-100PT-P20', 1),
        (36, 111, 'shopify', '2002', '9001', '3002', 'OLD-TOP-100PT-P20', 0);
      INSERT INTO channels.channel_listings(
        channel_id, product_variant_id, external_product_id,
        external_variant_id, external_url, sync_status
      ) VALUES
        (36, 101, '9001', '2001', 'https://example.test/active', 'synced'),
        (36, 111, '9001', '2002', 'https://example.test/archived', 'synced');
    `);
  });

  afterAll(async () => {
    await database?.close();
  });

  async function commandInput(idempotencyKey: string) {
    const context = await repository.loadChannelContext(36);
    const localProducts = await repository.listMappedProducts(36);
    const [group] = buildShopifyOwnershipGroups({
      channel: context.channel,
      localProducts: localProducts.map((product) => product.local),
      remoteProducts,
    });
    const recommendations = [{
      shopifyProductId: group.shopifyProductId,
      expectedPreviewHash: group.previewHash,
    }];
    const reason = "Detach reviewed inactive duplicate";
    const operator = "user:test";
    return {
      channel: context.channel,
      recommendations,
      remoteProducts,
      idempotencyKey,
      requestHash: shopifyOwnershipRepairRequestHash({
        channelId: 36,
        shopDomain: context.channel.shopDomain,
        recommendations,
        operator,
        reason,
      }),
      operator,
      reason,
      now: new Date("2026-09-12T20:00:00.000Z"),
    };
  }

  it("atomically detaches only the inactive owner and records immutable evidence", async () => {
    const log = vi.spyOn(console, "log").mockImplementation(() => undefined);
    try {
      const result = await repository.applyOwnershipRecommendations(
        await commandInput("123e4567-e89b-42d3-a456-426614174000"),
      );

      expect(result).toMatchObject({
        idempotentReplay: false,
        command: {
          channelId: 36,
          result: {
            resolvedGroupCount: 1,
            recommendedProductIds: [10],
            detachedProductIds: [11],
          },
        },
      });
      expect((await database.pool.query(`
        SELECT id, shopify_product_id
        FROM catalog.products
        ORDER BY id
      `)).rows).toEqual([
        { id: 10, shopify_product_id: "9001" },
        { id: 11, shopify_product_id: null },
      ]);
      expect((await database.pool.query(`
        SELECT shopify_variant_id, shopify_inventory_item_id
        FROM catalog.product_variants
        WHERE id = 111
      `)).rows[0]).toEqual({
        shopify_variant_id: null,
        shopify_inventory_item_id: null,
      });
      expect((await database.pool.query(`
        SELECT channel_product_id, channel_variant_id,
               channel_inventory_item_id, is_active
        FROM channels.channel_feeds
        WHERE product_variant_id = 111
      `)).rows[0]).toEqual({
        channel_product_id: null,
        channel_variant_id: null,
        channel_inventory_item_id: null,
        is_active: 0,
      });
      expect((await database.pool.query(`
        SELECT external_product_id, external_variant_id,
               external_url, sync_status, sync_error
        FROM channels.channel_listings
        WHERE product_variant_id = 111
      `)).rows[0]).toMatchObject({
        external_product_id: null,
        external_variant_id: null,
        external_url: null,
        sync_status: "error",
      });
      expect((await database.pool.query(`
        SELECT action, actor, context
        FROM public.audit_events
      `)).rows[0]).toMatchObject({
        action: "catalog.shopify_duplicate_ownership_resolved",
        actor: "user:test",
        context: { reason: "Detach reviewed inactive duplicate" },
      });
      await expect(database.pool.query(`
        UPDATE channels.shopify_ownership_repair_commands
        SET reason = 'tampered'
      `)).rejects.toMatchObject({ code: "55000" });
    } finally {
      log.mockRestore();
    }
  });

  it("atomically detaches every inert owner in one ownership group", async () => {
    const log = vi.spyOn(console, "log").mockImplementation(() => undefined);
    try {
      await database.pool.query(`
        INSERT INTO catalog.products(
          id, name, sku, shopify_product_id, shipping_group_id
        ) VALUES (12, 'Second inert shell', 'SHOPIFY-2003', '9001', 1)
      `);

      const result = await repository.applyOwnershipRecommendations(
        await commandInput("123e4567-e89b-42d3-a456-426614174010"),
      );

      expect(result).toMatchObject({
        idempotentReplay: false,
        command: {
          result: {
            resolvedGroupCount: 1,
            recommendedProductIds: [10],
            detachedProductIds: [11, 12],
            resolvedGroups: [{
              shopifyProductId: "9001",
              recommendedProductId: 10,
              detachedProductIds: [11, 12],
            }],
            clearedCatalogProductCount: 2,
          },
        },
      });
      expect((await database.pool.query(`
        SELECT id, shopify_product_id
        FROM catalog.products
        ORDER BY id
      `)).rows).toEqual([
        { id: 10, shopify_product_id: "9001" },
        { id: 11, shopify_product_id: null },
        { id: 12, shopify_product_id: null },
      ]);
    } finally {
      log.mockRestore();
    }
  });

  it("serializes concurrent retries and writes exactly one command and audit", async () => {
    const log = vi.spyOn(console, "log").mockImplementation(() => undefined);
    try {
      const input = await commandInput(
        "123e4567-e89b-42d3-a456-426614174001",
      );
      const results = await Promise.all([
        repository.applyOwnershipRecommendations(input),
        repository.applyOwnershipRecommendations(input),
      ]);

      expect(results.map((result) => result.idempotentReplay).sort())
        .toEqual([false, true]);
      expect((await database.pool.query(`
        SELECT count(*)::int AS count
        FROM channels.shopify_ownership_repair_commands
      `)).rows[0].count).toBe(1);
      expect((await database.pool.query(`
        SELECT count(*)::int AS count
        FROM public.audit_events
      `)).rows[0].count).toBe(1);
    } finally {
      log.mockRestore();
    }
  });

  it("rejects changed ownership evidence without writing any partial repair", async () => {
    const input = await commandInput(
      "123e4567-e89b-42d3-a456-426614174002",
    );
    await database.pool.query(`
      UPDATE catalog.product_variants
      SET is_active = true
      WHERE id = 111
    `);

    await expect(repository.applyOwnershipRecommendations(input))
      .rejects.toMatchObject({
        code: "SHOPIFY_OWNERSHIP_REPAIR_PREVIEW_STALE",
        statusCode: 409,
      });
    expect((await database.pool.query(`
      SELECT shopify_product_id
      FROM catalog.products
      WHERE id = 11
    `)).rows[0].shopify_product_id).toBe("9001");
    expect((await database.pool.query(`
      SELECT count(*)::int AS count
      FROM channels.shopify_ownership_repair_commands
    `)).rows[0].count).toBe(0);
    expect((await database.pool.query(`
      SELECT count(*)::int AS count
      FROM public.audit_events
    `)).rows[0].count).toBe(0);
  });
});
