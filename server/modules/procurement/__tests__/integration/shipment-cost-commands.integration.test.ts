  it("commits close finalization and history before waiting cost edits or cancellations can proceed", async () => {
    const command = await patch({ actualCents: 900 });
    let reportLocked!: () => void;
    let releaseClose!: () => void;
    const locked = new Promise<void>((resolveLocked) => { reportLocked = resolveLocked; });
    const release = new Promise<void>((resolveRelease) => { releaseClose = resolveRelease; });
    let pauseFirstLineRead = true;
    const closingStorage = {
      ...storage,
      async getInboundShipmentLines(...args: Parameters<typeof storage.getInboundShipmentLines>) {
        const lines = await storage.getInboundShipmentLines(...args);
        if (pauseFirstLineRead) {
          pauseFirstLineRead = false;
          reportLocked();
          await release;
        }
        return lines;
      },
      // This fixture proves procurement finalization. Inventory lot posting is
      // a separate existing post-commit operation and has no fixture candidates.
      async getProvisionalLotsByShipment() { return []; },
    };
    const closingService = createService(database, closingStorage as Parameters<typeof createService>[1], undefined, () => NOW);
    const closing = closingService.close(1, actorId, "Finalize fixture shipment")
      .then((value) => ({ ok: true as const, value }), (error: unknown) => ({ ok: false as const, error }));
    let editing: Promise<{ ok: true; value: unknown } | { ok: false; error: unknown }> | undefined;
    let cancelling: Promise<{ ok: true; value: unknown } | { ok: false; error: unknown }> | undefined;
    try {
      await Promise.race([locked, closing.then((result) => {
        if (!result.ok) throw result.error;
        throw new Error("Close completed without reaching the locked finalization boundary");
      })]);
      let reportPid!: (pid: number) => void;
      const ready = new Promise<number>((resolveReady) => { reportPid = resolveReady; });
      editing = database.transaction(async (tx) => {
        await tx.execute(sql`SET LOCAL statement_timeout = '8s'`);
        const result = await tx.execute(sql`SELECT pg_backend_pid() AS pid`);
        reportPid(Number(result.rows[0].pid));
        return service.executeCostCommandInTransaction(tx, command, actorId, NOW);
      }).then((value) => ({ ok: true as const, value }), (error: unknown) => ({ ok: false as const, error }));
      let reportCancelPid!: (pid: number) => void;
      const cancelReady = new Promise<number>((resolveReady) => { reportCancelPid = resolveReady; });
      const cancellationDatabase = {
        transaction: (work: (tx: unknown) => Promise<unknown>) => database.transaction(async (tx) => {
          await tx.execute(sql`SET LOCAL statement_timeout = '8s'`);
          const result = await tx.execute(sql`SELECT pg_backend_pid() AS pid`);
          reportCancelPid(Number(result.rows[0].pid));
          return work(tx);
        }),
      };
      const cancellingService = createService(cancellationDatabase, storage as Parameters<typeof createService>[1], undefined, () => NOW);
      cancelling = cancellingService.cancel(1, actorId, "Concurrent cancellation")
        .then((value) => ({ ok: true as const, value }), (error: unknown) => ({ ok: false as const, error }));
      const [editingPid, cancellationPid] = await Promise.all([ready, cancelReady]);
      await Promise.all([waitUntilBlocked(editingPid), waitUntilBlocked(cancellationPid)]);
      releaseClose();
      expect(await closing).toMatchObject({ ok: true, value: { status: "closed", closedBy: actorId, closedAt: NOW } });
      expect(await editing).toMatchObject({ ok: false, error: { details: { code: "SHIPMENT_COST_TERMINAL" } } });
      expect(await cancelling).toMatchObject({ ok: false, error: { statusCode: 400, message: "Cannot transition from 'closed' to 'cancelled'" } });
      expect((await readCost()).actualCents).toBe(500);
      expect(await database.select().from(schema.landedCostSnapshots)).toMatchObject([
        { inboundShipmentLineId: 11, totalLandedCostCents: 500, finalizedAt: NOW },
      ]);
      expect(await database.select().from(schema.inboundShipmentStatusHistory)).toMatchObject([
        { inboundShipmentId: 1, fromStatus: "costing", toStatus: "closed", changedBy: actorId, changedAt: NOW },
      ]);
    } finally {
      releaseClose();
      await Promise.allSettled([closing, ...(editing ? [editing] : []), ...(cancelling ? [cancelling] : [])]);
    }
  });

