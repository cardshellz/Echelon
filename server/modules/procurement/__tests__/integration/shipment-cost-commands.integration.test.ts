function identifier(value: string): string {
  return `"${value.replaceAll('"', '""')}"`;
}

function defaultExpression(value: unknown): string {
  if (value instanceof SQL) {
    const query = new PgDialect().sqlToQuery(value);
    if (query.params.length !== 0) throw new Error("Fixture default must not contain parameters");
    return query.sql;
  }
  if (typeof value === "string") return `'${value.replaceAll("'", "''")}'`;
  if (typeof value === "number" || typeof value === "boolean") return String(value);
  throw new Error("Unsupported schema default in shipment-cost fixture");
}

/** Full real column definitions/defaults; only the relevant cross-table FKs are installed below. */
function fixtureTable(table: Parameters<typeof getTableConfig>[0]): string {
  const definition = getTableConfig(table);
  const columns = Object.values(getTableColumns(table as Table)).map((column) => {
    if (column.primary && column.name === "id") {
      const type = column.getSQLType().includes("big") ? "bigint" : "integer";
      return `${identifier(column.name)} ${type} GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY`;
    }
    const defaultSql = column.default === undefined ? "" : ` DEFAULT ${defaultExpression(column.default)}`;
    return `${identifier(column.name)} ${column.getSQLType()}${defaultSql}${column.notNull ? " NOT NULL" : ""}`;
  });
  return `CREATE TABLE ${identifier(definition.schema ?? "public")}.${identifier(definition.name)} (${columns.join(", ")})`;
}

