import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import { getTableColumns, type Table } from "drizzle-orm";
import { getTableConfig } from "drizzle-orm/pg-core";
import { drizzle } from "drizzle-orm/node-postgres";
import pg from "pg";
import { beforeAll, beforeEach, afterAll, describe, expect, it } from "vitest";
import * as schema from "@shared/schema";
import { createShipmentHistoryCorrectionService, shipmentHistoryScope } from "../../shipment-history-correction.service";
import { historyFingerprint } from "../../shipment-history-correction.repository";
import { historyInput } from "../../../../../test/fixtures/shipment-history-correction";

const url = process.env.ECHELON_TEST_DATABASE_URL;
const suite = url && process.env.ECHELON_TEST_DATABASE_DISPOSABLE === "true" ? describe : describe.skip;
const now = new Date("2026-10-23T12:00:00Z");
const tables = [schema.inboundShipments, schema.inboundShipmentLines, schema.purchaseOrders, schema.purchaseOrderLines,
  schema.receivingOrders, schema.receivingLines, schema.poReceipts, schema.receiptReversals,
  schema.inboundFreightCosts, schema.inboundFreightAllocations, schema.landedCostSnapshots, schema.landedCostAdjustments,
  schema.inboundShipmentStatusHistory];
suite.sequential("shipment history correction PostgreSQL guarantees", () => {
  let pool: pg.Pool;
  let service: ReturnType<typeof createShipmentHistoryCorrectionService>;
  const owned: string[] = [];
  let ledgerOwned = false;
  beforeAll(async () => {
    if (!url || !["127.0.0.1", "localhost"].includes(new URL(url).hostname) || [process.env.DATABASE_URL, process.env.EXTERNAL_DATABASE_URL].includes(url)) throw new Error("Requires an isolated local disposable database");
    pool = new pg.Pool({ connectionString: url, max: 5, statement_timeout: 10000 });
    for (const name of ["procurement", "identity"]) { await pool.query(`CREATE SCHEMA ${name}`); owned.push(name); }
    for (const table of tables) {
      const config = getTableConfig(table);
      const columns = Object.values(getTableColumns(table as Table)).map(column => `"${column.name}" ${column.getSQLType()}${column.primary ? " GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" : ""}`);
      await pool.query(`CREATE TABLE "${config.schema}"."${config.name}" (${columns.join(",")})`);
    }
    await pool.query(`CREATE TABLE identity.users(id varchar PRIMARY KEY,active integer,display_name text,username text);
      CREATE TABLE identity.auth_roles(id integer PRIMARY KEY,name text,is_system integer);
      CREATE TABLE identity.auth_user_roles(id integer PRIMARY KEY,user_id varchar,role_id integer);
      CREATE TABLE identity.auth_permissions(id integer PRIMARY KEY,resource text,action text);
      CREATE TABLE identity.auth_role_permissions(id integer PRIMARY KEY,role_id integer,permission_id integer,constraints jsonb);`);
    if ((await pool.query("SELECT to_regclass('public.financial_command_results') AS name")).rows[0].name) throw new Error("Test command ledger already exists; refusing to reuse it");
    ledgerOwned = true;
    for (const migration of ["136_financial_command_results.sql", "140_financial_command_operations.sql", "900000028000019050001_shipment_history_corrections.sql"]) {
      await pool.query(readFileSync(resolve(process.cwd(), "migrations", migration), "utf8"));
    }
    service = createShipmentHistoryCorrectionService(drizzle(pool, { schema }), () => now);
  });
  beforeEach(async () => {
    await pool.query(`BEGIN;
      ALTER TABLE procurement.shipment_history_corrections DISABLE TRIGGER shipment_history_correction_no_truncate;
      TRUNCATE procurement.shipment_history_corrections;
      TRUNCATE ${tables.map(table => { const c = getTableConfig(table); return `"${c.schema}"."${c.name}"`; }).join(",")},
        identity.users,identity.auth_roles,identity.auth_user_roles,identity.auth_permissions,identity.auth_role_permissions,
        public.financial_command_results CASCADE;
      ALTER TABLE procurement.shipment_history_corrections ENABLE TRIGGER shipment_history_correction_no_truncate;
      INSERT INTO identity.users VALUES ('admin',1,'Purchasing Administrator','admin'),('viewer',1,'Viewer','viewer');
      INSERT INTO identity.auth_roles VALUES (1,'Administrator',1);
      INSERT INTO identity.auth_user_roles VALUES (1,'admin',1);
      INSERT INTO identity.auth_permissions VALUES (1,'purchasing','approve');
      INSERT INTO identity.auth_role_permissions VALUES (1,1,1,null);
      INSERT INTO procurement.inbound_shipments (id,shipment_number,status,total_pieces,actual_total_cost_cents,estimated_total_cost_cents,updated_at)
        VALUES (42,'TEST-SHIP-42','booked',100000,165191,165191,'2026-03-19T12:00:00Z');
      INSERT INTO procurement.purchase_orders (id,po_number,status,physical_status,financial_status,total_cents) VALUES (17,'TEST-PO-17','closed','received','paid',238000);
      INSERT INTO procurement.purchase_order_lines (id,purchase_order_id,order_qty,received_qty,line_total_cents) VALUES (101,17,200000,200000,120000);
      INSERT INTO procurement.inbound_shipment_lines (id,inbound_shipment_id,purchase_order_id,purchase_order_line_id,sku,qty_shipped,allocated_cost_cents)
        VALUES (201,42,17,101,'TEST-SLEEVES',100000,165191);
      INSERT INTO procurement.receiving_orders (id,receipt_number,purchase_order_id,status) VALUES (31,'TEST-RECEIPT-31',17,'closed'),(32,'TEST-RECEIPT-32',17,'closed');
      INSERT INTO procurement.receiving_lines (id,receiving_order_id,purchase_order_line_id,received_qty) VALUES (301,31,101,10),(302,32,101,10);
      INSERT INTO procurement.po_receipts (id,purchase_order_id,purchase_order_line_id,receiving_order_id,receiving_line_id,qty_received)
        VALUES (401,17,101,31,301,200000),(402,17,101,32,302,100000);
      INSERT INTO procurement.inbound_freight_costs (id,inbound_shipment_id,currency,actual_cents,estimated_cents) VALUES (501,42,'USD',165200,165200),(502,42,'USD',-9,-9);
      INSERT INTO procurement.inbound_freight_allocations (id,shipment_cost_id,inbound_shipment_line_id,allocated_cents) VALUES (601,501,201,165200),(602,502,201,-9);
      INSERT INTO procurement.landed_cost_snapshots (id,inbound_shipment_line_id) VALUES (701,201);
      INSERT INTO procurement.landed_cost_adjustments (id,inbound_shipment_line_id,adjustment_amount_cents) VALUES (801,201,20);
      INSERT INTO procurement.inbound_shipment_status_history (inbound_shipment_id,from_status,to_status,changed_at,notes)
        VALUES (42,'draft','booked','2026-03-19T12:00:00Z','Shipment booked');
      COMMIT;`);
  });
  afterAll(async () => {
    if (!pool) return;
    try {
      if (ledgerOwned) await pool.query("DROP TABLE IF EXISTS public.financial_command_recoveries,public.financial_command_results CASCADE");
      for (const name of owned.reverse()) await pool.query(`DROP SCHEMA ${name} CASCADE`);
    } finally { await pool.end(); }
  });
  async function prepare(actor = "admin") {
    const context = await service.context(42, actor);
    const input = historyInput(context.sourceVersion);
    const preview = await service.preview(42, input, actor);
    return { ...input, previewVersion: preview.previewVersion };
  }
  async function approve(input: Awaited<ReturnType<typeof prepare>>, key: string, actorId = "admin") {
    return service.approve(42, input, actorId, { ...shipmentHistoryScope(42), actorType: "user", actorId,
      idempotencyKey: key, requestHash: historyFingerprint(input) });
  }
  async function protectedState() {
    const result = [];
    for (const table of tables.filter(table => table !== schema.inboundShipments && table !== schema.inboundShipmentStatusHistory)) {
      const c = getTableConfig(table); result.push((await pool.query(`SELECT * FROM "${c.schema}"."${c.name}" ORDER BY id`)).rows);
    }
    return result;
  }
  it("shows the conflicting history without borrowing PO quantities or linking receipts", async () => {
    const context = await service.context(42, "admin");
    expect(context.lines[0]).toMatchObject({ pieces: 100000, receivedPieces: 200000, postedReceiptPieces: 300000 });
    expect(context.receipts.every(receipt => receipt.shipmentId === null && receipt.piecesPerUnit === null)).toBe(true);
    expect(context.charges).toEqual([{ currency: "USD", cents: 165191 }]);
    expect(context.issues).toHaveLength(3);
  });
  it("previews without writes, commits one immutable approval, preserves costs and closed PO, and replays lost responses", async () => {
    const before = await protectedState(), input = await prepare();
    expect(await protectedState()).toEqual(before);
    expect((await pool.query("SELECT status FROM procurement.inbound_shipments WHERE id=42")).rows[0].status).toBe("booked");
    const first = await approve(input, "history-approve-1");
    expect(first.httpStatus).toBe(200);
    expect(await protectedState()).toEqual(before);
    expect((await pool.query("SELECT status FROM procurement.inbound_shipments WHERE id=42")).rows[0].status).toBe("delivered");
    const replay = await approve(input, "history-approve-1");
    expect(replay).toMatchObject({ httpStatus: 200, replayed: true, body: first.body });
    const after = await service.context(42, "admin");
    expect(after.approvals).toHaveLength(1);
    expect(after.approvals[0]).toMatchObject({ actorId: "admin", actorName: "Purchasing Administrator", review: { shippedPiecesBefore: 0, shippedPiecesAfter: 100000 } });
    expect(after.issues).toHaveLength(3);
    await expect(pool.query("UPDATE procurement.shipment_history_corrections SET reason='Overwrite approved history'")).rejects.toThrow(/immutable/);
    await expect(pool.query("DELETE FROM procurement.shipment_history_corrections")).rejects.toThrow(/immutable/);
    await expect(pool.query("TRUNCATE procurement.shipment_history_corrections")).rejects.toThrow(/immutable/);
  });
  it.each(["permission", "active", "scoped"])("rechecks %s before approval", async kind => {
    const input = await prepare();
    if (kind === "permission") await pool.query("DELETE FROM identity.auth_role_permissions");
    if (kind === "active") await pool.query("UPDATE identity.users SET active=0 WHERE id='admin'");
    if (kind === "scoped") await pool.query("UPDATE identity.auth_role_permissions SET constraints='{}'");
    expect(await approve(input, `revoked-${kind}`)).toMatchObject({ httpStatus: 403 });
    expect((await pool.query("SELECT count(*) FROM procurement.shipment_history_corrections")).rows[0].count).toBe("0");
  });
  it.each(["manifest", "receipt", "cost"])("rejects a stale %s preview without changing records", async kind => {
    const input = await prepare();
    if (kind === "manifest") await pool.query("UPDATE procurement.inbound_shipment_lines SET qty_shipped=100001 WHERE id=201");
    if (kind === "receipt") await pool.query("UPDATE procurement.po_receipts SET qty_received=200001 WHERE id=401");
    if (kind === "cost") await pool.query("UPDATE procurement.inbound_freight_costs SET actual_cents=165201 WHERE id=501");
    expect(await approve(input, `stale-${kind}`)).toMatchObject({ httpStatus: 409, body: { code: "SHIPMENT_HISTORY_STALE" } });
  });
  it("rejects tampered before/after and two concurrent approvals apply only once", async () => {
    const input = await prepare();
    expect(await approve({ ...input, departedOn: "2026-03-13" }, "tampered")).toMatchObject({ httpStatus: 409, body: { code: "SHIPMENT_HISTORY_PREVIEW_CHANGED" } });
    const results = await Promise.all([approve(input, "concurrent-a"), approve(input, "concurrent-b")]);
    expect(results.map(result => result.httpStatus).sort()).toEqual([200, 409]);
    expect((await pool.query("SELECT count(*) FROM procurement.shipment_history_corrections")).rows[0].count).toBe("1");
  });
  it("rolls back status and audit if a protected cost changes during the write", async () => {
    const input = await prepare(), before = await protectedState();
    await pool.query(`CREATE FUNCTION procurement.test_unexpected_cost_change() RETURNS trigger LANGUAGE plpgsql AS $$
      BEGIN UPDATE procurement.inbound_freight_costs SET actual_cents=actual_cents+1 WHERE id=501; RETURN NEW; END $$;
      CREATE TRIGGER test_cost_change AFTER UPDATE ON procurement.inbound_shipments FOR EACH ROW EXECUTE FUNCTION procurement.test_unexpected_cost_change();`);
    try {
      expect(await approve(input, "protect-money")).toMatchObject({ httpStatus: 409, body: { code: "SHIPMENT_HISTORY_PROTECTED_RECORD_CHANGED" } });
      expect(await protectedState()).toEqual(before);
      expect((await pool.query("SELECT status FROM procurement.inbound_shipments WHERE id=42")).rows[0].status).toBe("booked");
      expect((await pool.query("SELECT count(*) FROM procurement.shipment_history_corrections")).rows[0].count).toBe("0");
    } finally { await pool.query("DROP TRIGGER test_cost_change ON procurement.inbound_shipments; DROP FUNCTION procurement.test_unexpected_cost_change()"); }
  });
  it("handles a shared shipment and a split PO line without reallocating either PO's cost share", async () => {
    await pool.query(`INSERT INTO procurement.purchase_orders (id,po_number,status,physical_status) VALUES (99,'TEST-PO-99','received','received');
      INSERT INTO procurement.purchase_order_lines (id,purchase_order_id,order_qty,received_qty) VALUES (102,99,50000,50000);
      INSERT INTO procurement.inbound_shipments (id,shipment_number,status) VALUES (43,'TEST-SHIP-43','closed');
      INSERT INTO procurement.inbound_shipment_lines (id,inbound_shipment_id,purchase_order_id,purchase_order_line_id,sku,qty_shipped,allocated_cost_cents)
        VALUES (202,42,99,102,'OTHER-PO',50000,10000),(203,43,17,101,'TEST-SLEEVES',100000,20000);
      INSERT INTO procurement.inbound_freight_costs (id,inbound_shipment_id,currency,actual_cents) VALUES (503,42,'USD',10000),(504,43,'USD',20000);
      INSERT INTO procurement.inbound_freight_allocations (id,shipment_cost_id,inbound_shipment_line_id,allocated_cents) VALUES (603,503,202,10000),(604,504,203,20000);`);
    const context = await service.context(42, "admin");
    expect(context.lines[0]).toMatchObject({ purchaseOrderId: 17, pieces: 100000, otherShippedPieces: 100000 });
    expect(context.lines[1]).toMatchObject({ purchaseOrderId: 99, pieces: 50000, postedReceiptPieces: null });
    const before = await protectedState();
    const result = await approve(await prepare(), "multi-po-history");
    expect(result).toMatchObject({ httpStatus: 200, body: { review: { shippedPiecesAfter: 150000, charges: [{ currency: "USD", cents: 175191 }] } } });
    expect(await protectedState()).toEqual(before);
    expect((await pool.query("SELECT status FROM procurement.inbound_shipments WHERE id=43")).rows[0].status).toBe("closed");
  });
  it("rejects invalid saved quantities as source errors instead of blaming approval input", async () => {
    await pool.query("UPDATE procurement.inbound_shipment_lines SET qty_shipped=-1 WHERE id=201");
    await expect(service.context(42, "admin")).rejects.toMatchObject({ code: "SHIPMENT_HISTORY_SOURCE_INVALID", statusCode: 409 });
  });
});
